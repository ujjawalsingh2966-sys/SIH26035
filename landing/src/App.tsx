function LinkOrUnavailable({ href, children, className }: { href: string; children: React.ReactNode; className: string }) {
  return href ? <a href={href} className={className} target={href.startsWith('http') ? '_blank' : undefined} rel={href.startsWith('http') ? 'noopener noreferrer' : undefined}>{children}</a> : <span className={className + ' is-unavailable'} title="Link not configured" aria-disabled="true">{children} <small>Not configured</small></span>
}

